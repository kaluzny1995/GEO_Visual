def _clean_code(value: object) -> str:
    """Normalise a country or subdivision code for dictionary lookup."""
    if value is None:
        return ""
    text = str(value).strip()
    if text.lower() in {"", "none", "nan", "<na>"}:
        return ""
    return text.upper()


def country_name(code: object) -> str:
    """Return the full country name for an ISO alpha-2 code, or an empty string."""
    return COUNTRY_NAMES.get(_clean_code(code), "")


def subdivision_name(country_code: object, state_province: object) -> str:
    """Return the full first-level region name for a country/region code pair."""
    country = _clean_code(country_code)
    subdivision = _clean_code(state_province)
    if not country or not subdivision:
        return ""
    return SUBDIVISION_NAMES.get((country, subdivision), "")


def region_name(country_code: object, state_province: object) -> str:
    """Return ``Country - Region`` using full names, or whichever part is known."""
    country = country_name(country_code)
    subdivision = subdivision_name(country_code, state_province)
    if country and subdivision:
        return f"{country} - {subdivision}"
    return country or subdivision


def contains_subdivision_name(country_code: object, text: object) -> bool:
    """Return whether text already mentions a known region of the country."""
    country = _clean_code(country_code)
    haystack = str(text).casefold()
    if not country or not haystack:
        return False
    return any(
        subdivision_country == country and name.casefold() in haystack
        for (subdivision_country, _), name in SUBDIVISION_NAMES.items()
    )
